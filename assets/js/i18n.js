function setLang(lang) {
    if (!i18nData[lang]) lang = 'en';
    localStorage.setItem('lang', lang);
    document.documentElement.lang = lang;

    var dict = i18nData[lang];
    var els = document.querySelectorAll('[data-i18n]');
    for (var i = 0; i < els.length; i++) {
        var key = els[i].getAttribute('data-i18n');
        if (dict[key] !== undefined) {
            els[i].textContent = dict[key];
        }
    }

    // Update placeholders
    var searchInput = document.getElementById('search-text');
    if (searchInput && dict['search_placeholder']) {
        searchInput.placeholder = dict['search_placeholder'];
    }
    var mSearchInput = document.getElementById('m_search-text');
    if (mSearchInput && dict['search_placeholder']) {
        mSearchInput.placeholder = dict['search_placeholder'];
    }

    // Update active language button
    var btns = document.querySelectorAll('.lang-switch .lang-btn');
    for (var j = 0; j < btns.length; j++) {
        btns[j].classList.toggle('active', btns[j].getAttribute('data-lang') === lang);
    }

    // Update dark mode tooltip
    var night = document.cookie.replace(/(?:(?:^|.*;\s*)night\s*\=\s*([^;]*).*$)|^.*$/, "$1") || '0';
    var darkModeBtn = document.querySelector('.switch-dark-mode');
    if (darkModeBtn) {
        if (night === '1') {
            darkModeBtn.setAttribute('data-original-title', dict['day_mode']);
        } else {
            darkModeBtn.setAttribute('data-original-title', dict['night_mode']);
        }
    }
}

function initLang() {
    var lang = localStorage.getItem('lang') || 'en';
    setLang(lang);
}

document.addEventListener('DOMContentLoaded', initLang);
